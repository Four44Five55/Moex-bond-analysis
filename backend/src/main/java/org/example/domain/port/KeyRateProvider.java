package org.example.domain.port;

/**
 * Источник ключевой ставки ЦБ. Нужен налогу по вкладам: необлагаемый вычет равен
 * 1 млн ₽ × <b>максимальной</b> ключевой ставке на 1-е число каждого месяца года.
 */
public interface KeyRateProvider {

    /**
     * @param year календарный год
     * @return максимальная ключевая ставка на 1-е число месяцев этого года, %
     *         (для текущего года — по уже наступившие месяцы)
     */
    double maxKeyRateForYear(int year);
}
